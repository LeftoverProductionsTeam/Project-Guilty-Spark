//! Game-native camera points + HaloScript. The game renders at its own resolution;
//! player input stays enabled. No process injection, OBS capture or HUD mockup.
use crate::{
    build::Runner,
    creative::{CameraShot, EngineMachinima},
    invalid,
    project::{self, Project},
    safe_relative, Result, SparkError,
};
use std::{fs, path::Path};
/// Extend an already owned conversion job for a take. Used by acceptance tools;
/// installed SDK masters and unrelated folders are refused.
pub fn prepare_workspace_take(
    project: &Project,
    scenario: &str,
    workspace: &Path,
    edit: &Path,
    original_scripts: usize,
    on_event: impl Fn(crate::build::JobEvent) + Send + Sync,
) -> Result<()> {
    project.validate()?;
    crate::reject_links(workspace)?;
    crate::reject_links(edit)?;
    let workspace = fs::canonicalize(workspace)?;
    let workspace = workspace.as_path();
    let edit = fs::canonicalize(edit)?;
    let edit = edit.as_path();
    let source = project
        .source
        .as_ref()
        .ok_or_else(|| SparkError::Invalid("An owned converted source is required".into()))?;
    let marker: serde_json::Value =
        serde_json::from_slice(&fs::read(workspace.join("conversion-manifest.json"))?)?;
    if marker
        .get("sourceSha256")
        .and_then(serde_json::Value::as_str)
        != Some(source.sha256.as_str())
        || source.scenario_path != scenario
        || !workspace.join("input-sdk-tags.json").is_file()
    {
        return invalid("Engine take workspace is not the matching owned conversion job");
    }
    let cancel = std::sync::atomic::AtomicBool::new(false);
    let id = uuid::Uuid::new_v4().to_string();
    let runner = Runner {
        id: &id,
        project: &project.id,
        cancel: &cancel,
        event: &on_event,
    };
    prepare(
        project,
        scenario,
        workspace,
        edit,
        &runner,
        original_scripts,
    )
}
pub fn prepare_workspace_animations(
    project: &Project,
    inspection: &crate::maps::MapInspection,
    workspace: &Path,
    tools: &crate::build::Toolchain,
    on_event: impl Fn(crate::build::JobEvent) + Send + Sync,
) -> Result<()> {
    project.validate()?;
    crate::reject_links(workspace)?;
    let workspace = fs::canonicalize(workspace)?;
    let marker: serde_json::Value =
        serde_json::from_slice(&fs::read(workspace.join("conversion-manifest.json"))?)?;
    if marker
        .get("sourceSha256")
        .and_then(serde_json::Value::as_str)
        != Some(inspection.sha256.as_str())
        || !workspace.join("input-sdk-tags.json").is_file()
    {
        return invalid("Animation workspace is not the matching owned conversion job");
    }
    let cancel = std::sync::atomic::AtomicBool::new(false);
    let id = uuid::Uuid::new_v4().to_string();
    let runner = Runner {
        id: &id,
        project: &project.id,
        cancel: &cancel,
        event: &on_event,
    };
    crate::animations::prepare_native(project, inspection, tools, &workspace, &runner)?;
    Ok(())
}
pub fn camera_angles(shot: &CameraShot) -> Result<[f32; 3]> {
    let d: Vec<_> = shot
        .look_at
        .iter()
        .zip(shot.camera_position)
        .map(|(a, b)| a - b)
        .collect();
    let length = d.iter().map(|v| v * v).sum::<f32>().sqrt();
    if !length.is_finite() || length < 0.001 {
        return invalid("Engine camera needs a distinct finite look-at target");
    }
    Ok([
        d[1].atan2(d[0]),
        (d[2] / length).clamp(-1., 1.).asin(),
        shot.roll.unwrap_or(0.).to_radians(),
    ])
}
pub fn script(names: &[String], shots: &[CameraShot], options: &EngineMachinima) -> Result<String> {
    if names.len() != shots.len()
        || names.is_empty()
        || names.len() > 64
        || names
            .iter()
            .any(|n| n.len() > 31 || !n.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_'))
    {
        return invalid("Invalid engine camera binding");
    }
    let selected = options
        .camera_id
        .as_ref()
        .and_then(|id| shots.iter().position(|s| &s.id == id))
        .unwrap_or(0);
    let mut h=String::from("; Generated by Project Guilty Spark. Native game camera, full game resolution.\n; Flashlight toggles the take. Player movement and actions remain enabled.\n(global boolean gs_mc_active false)\n(global boolean gs_mc_ready false)\n(global boolean gs_mc_flash false)\n(script static void gs_record_stop\n  (set gs_mc_active false)\n  (camera_control false)\n  (show_hud true)\n  (cinematic_show_letterbox false)\n  (player_enable_input true)\n  (log_print \"Spark camera stopped; HUD restored\")\n)\n(script static void gs_record_start\n  (camera_control true)\n  (show_hud false)\n  (cinematic_show_letterbox false)\n  (player_enable_input true)\n");
    h.push_str(&format!("  (camera_set {} 0)\n  (set gs_mc_active true)\n  (log_print \"Spark camera active; actor controls enabled\")\n)\n",names[selected]));
    h.push_str("(script startup gs_mc_initialize\n  (sleep_until (> (list_count (players)) 0) 1)\n  (set gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0))))\n  (set gs_mc_ready true)\n");
    if options.auto_start {
        h.push_str("  (gs_record_start)\n");
    }
    h.push_str(")\n(script continuous gs_mc_controls\n  (sleep_until gs_mc_ready 1)\n  (if (> (list_count (players)) 0)\n    (if (not (= gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0)))))\n      (begin\n        (set gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0))))\n        (if gs_mc_active (gs_record_stop) (gs_record_start))\n      )\n    )\n  )\n  (sleep 1)\n)\n");
    if options.playback == "sequence" {
        h.push_str("(script continuous gs_mc_sequence\n  (sleep_until gs_mc_active 1)\n");
        for (i, name) in names.iter().enumerate() {
            let duration =
                ((shots[i].duration_ms as f64 * 30. / 1000.).round() as u32).clamp(1, 30000);
            let blend = if i == 0 || shots[i].easing.as_deref() == Some("cut") {
                0
            } else {
                duration
            };
            h.push_str(&format!("  (if gs_mc_active (begin (camera_set {name} {blend}) (sleep_until (not gs_mc_active) 1 {duration})))\n"));
        }
        h.push_str("  (if gs_mc_active (gs_record_stop))\n)\n");
    }
    Ok(h)
}
pub(crate) fn prepare(
    project: &Project,
    scenario: &str,
    workspace: &Path,
    edit: &Path,
    runner: &Runner,
    original_scripts: usize,
) -> Result<()> {
    prepare_source(project,scenario,workspace,edit,runner,Some(original_scripts))
}
/// Fresh authored source already owns its exported logic modules. Reuse those
/// exact files; recovering over them would discard the source of the mission.
pub(crate) fn prepare_authored(project:&Project,scenario:&str,workspace:&Path,edit:&Path,runner:&Runner)->Result<()> {
    prepare_source(project,scenario,workspace,edit,runner,None)
}
fn authored_source_hashes(project:&Project,scenario:&str,workspace:&Path,names:&[String])->Result<std::collections::BTreeMap<String,String>> {
    let doc=project.quick_forge.as_ref().filter(|doc|doc.native.is_none()&&doc.runtime_id==crate::runtime::RuntimeId::MccSteam)
        .ok_or_else(||SparkError::Invalid("Native authored camera controls need editable MCC source".into()))?;
    crate::native_logic::verify_exported_sources(doc,workspace,scenario)?;
    let modules=crate::native_logic::source_modules(doc)?;
    let mut expected=std::collections::BTreeSet::new();
    let directory=crate::native_logic::script_path(workspace,scenario)?.parent().unwrap().to_owned();
    let mut hashes=std::collections::BTreeMap::new();
    for module in modules {
        let name=module.filename.strip_suffix(".hsc").ok_or_else(||SparkError::Invalid("Authored camera source has an invalid module name".into()))?.to_owned();
        if !expected.insert(name) {return invalid("Duplicate authored camera source module");}
        let relative=directory.join(&module.filename).strip_prefix(workspace).map_err(|_|SparkError::Invalid("Authored camera source escaped its job".into()))?.to_string_lossy().replace('\\',"/");
        hashes.insert(relative,module.sha256);
    }
    if names.len()+1>16 {return invalid("The scenario has no source-module slot for the generated camera source");}
    let globals=crate::native_logic::ensure_h1a_global_source(workspace)?;
    if !globals.is_file()||fs::read(&globals)?!=crate::native_logic::H1A_EMPTY_GLOBAL_SOURCE {return invalid("Authored camera merge requires its exact generated global support file; unrelated globals are preserved");}
    hashes.insert("data/global_scripts.hsc".into(),crate::maps::hash_file(&globals)?);
    // The native compiler may omit a comment-only globals module. Every actual
    // level module must still be present exactly once, with no unrelated source.
    let actual:std::collections::BTreeSet<_>=names.iter().filter(|name|name.as_str()!="global_scripts").cloned().collect();
    if actual!=expected||names.len()!=actual.len()+usize::from(names.iter().any(|name|name=="global_scripts")) {return invalid("Native authored source-module inventory differs from the exported mission/logic files");}
    Ok(hashes)
}
fn prepare_source(
    project: &Project,
    scenario: &str,
    workspace: &Path,
    edit: &Path,
    runner: &Runner,
    original_scripts: Option<usize>,
) -> Result<()> {
    let Some(studio) = &project.studio else {
        return Ok(());
    };
    let Some(options) = studio.engine_machinima.as_ref().filter(|o| o.enabled) else {
        return Ok(());
    };
    studio.validate()?;
    let tags = workspace.join("tags");
    let tag = format!("{scenario}.scenario");
    let scenario_path=safe_relative(scenario)?;
    let generated_source=workspace.join("data").join(scenario_path.parent().unwrap_or(Path::new(""))).join("scripts/gs_machinima.hsc");
    crate::reject_links(&generated_source)?;
    if generated_source.exists() {return invalid("The camera source file already exists in this job. Preserve/review its contents before preparing another take");}
    // Read the owned native scenario, not a guessed cache offset or script name.
    // Invader 696830ff: edit -C/-G and recover's ordinary scenario source output.
    let read_names = |field: &str, limit: usize| -> Result<Vec<String>> {
        let count = runner.run(edit,&["-t".into(),tags.to_string_lossy().into_owned(),"-C".into(),field.into(),tag.clone()],workspace,"engine-script-readback",46)?
            .trim().parse::<usize>().map_err(|_|SparkError::Invalid(format!("Native {field} count unavailable")))?;
        if count > limit {return invalid(format!("Native {field} exceed the selected scenario bound"));}
        if count == 0 {return Ok(vec![]);}
        let output = runner.run(edit,&["-t".into(),tags.to_string_lossy().into_owned(),"-G".into(),format!("{field}[*].name"),tag.clone()],workspace,"engine-script-readback",46)?;
        let names:Vec<_> = output.lines().map(str::to_owned).collect();
        if names.len()!=count || names.iter().any(|name|name.is_empty()||name.chars().any(char::is_control)) {
            return invalid(format!("Native {field} names do not match their array count"));
        }
        Ok(names)
    };
    let inherited_scripts=read_names("scripts",1024)?;
    let inherited_globals=read_names("globals",512)?;
    let inherited_sources=read_names("source_files",16)?;
    if original_scripts.is_some_and(|count|inherited_scripts.len()!=count) {
        return invalid("The staged scenario script inventory differs from the source cache. Reconcile its source before adding camera controls");
    }
    let generated_scripts=if options.playback=="sequence" {5} else {4};
    if inherited_scripts.len()+generated_scripts>1024 || inherited_globals.len()+3>512 {
        return invalid("The existing script/global tables have no capacity for this native camera take");
    }
    let reserved=["gs_record_stop","gs_record_start","gs_mc_initialize","gs_mc_controls","gs_mc_sequence","gs_mc_active","gs_mc_ready","gs_mc_flash"];
    if inherited_scripts.iter().chain(&inherited_globals).any(|name|reserved.iter().any(|reserved|name.eq_ignore_ascii_case(reserved))) {
        return invalid("Existing gameplay owns a generated camera script/global name. Keep that source and resolve the name collision before adding camera controls");
    }
    let mut recovered_sources=std::collections::BTreeMap::<String,String>::new();
    let mut source_recovery_tool=None;
    if original_scripts.is_none() {
        recovered_sources=authored_source_hashes(project,scenario,workspace,&inherited_sources)?;
    } else if !inherited_scripts.is_empty() || !inherited_globals.is_empty() || !inherited_sources.is_empty() {
        if inherited_sources.is_empty() {
            return invalid("Existing gameplay scripts/globals have no recoverable source modules. Recover and review their source first; Spark will not replace them");
        }
        crate::source_recovery::validate_output_names(&inherited_sources.join("\n"))?;
        let mut names=std::collections::BTreeSet::new();
        for name in &inherited_sources {
            if !names.insert(name.to_ascii_lowercase()) || name.eq_ignore_ascii_case("gs_machinima") {
                return invalid("Recovered script filenames collide with each other or the camera module; no source was overwritten");
            }
        }
        if inherited_sources.len()+1>16 {return invalid("The scenario has no source-module slot for the generated camera source");}
        let parent=safe_relative(scenario)?;
        let source_directory=workspace.join("data").join(parent.parent().unwrap_or(Path::new(""))).join("scripts");
        let mut paths=vec![];
        for name in &inherited_sources {
            let path=if name=="global_scripts" {workspace.join("data/global_scripts.hsc")} else {source_directory.join(format!("{name}.hsc"))};
            crate::reject_links(&path)?;
            if path.exists() {return invalid("A recovered script destination already exists in this job. Review the staged source rather than overwriting authored files");}
            paths.push(path);
        }
        let recover=edit.parent().ok_or_else(||SparkError::Invalid("Native recovery tool folder unavailable".into()))?
            .join(if cfg!(windows) {"invader-recover.exe"} else {"invader-recover"});
        crate::reject_links(&recover)?;
        if !recover.is_file() {return invalid("Preserving existing gameplay while adding a camera take requires invader-recover alongside invader-edit");}
        let recover_hash=crate::maps::hash_file(&recover)?;
        let scenario_file=tags.join(safe_relative(&tag)?);
        let scenario_hash=crate::maps::hash_file(&scenario_file)?;
        runner.run(&recover,&["-t".into(),tags.to_string_lossy().into_owned(),"-d".into(),workspace.join("data").to_string_lossy().into_owned(),tag.clone()],workspace,"engine-script-recovery",47)?;
        if crate::maps::hash_file(&recover)?!=recover_hash || crate::maps::hash_file(&scenario_file)?!=scenario_hash {
            return invalid("Native recovery changed its executable or source scenario; the derived job is not accepted");
        }
        source_recovery_tool=Some(recover_hash);
        for path in paths {
            crate::reject_links(&path)?;
            let size=fs::metadata(&path).map_err(|problem|SparkError::Invalid(format!("Native recovery did not provide source module {}: {problem}",path.file_name().unwrap_or_default().to_string_lossy())))?.len();
            if !path.is_file() || size>1024*1024 {return invalid("Recovered script module is missing or exceeds the native source bound");}
            let relative=path.strip_prefix(workspace).map_err(|_|SparkError::Invalid("Recovered source escaped the owned job".into()))?.to_string_lossy().replace('\\',"/");
            recovered_sources.insert(relative,crate::maps::hash_file(&path)?);
        }
    }
    let args = vec![
        "-t".into(),
        tags.to_string_lossy().into_owned(),
        "-C".into(),
        "cutscene_camera_points".into(),
        tag.clone(),
    ];
    let count = runner
        .run(edit, &args, workspace, "engine-camera", 48)?
        .trim()
        .parse::<usize>()
        .map_err(|_| SparkError::Invalid("Camera point count unavailable".into()))?;
    if count + studio.shots.len() > 512 {
        return invalid("Engine camera points exceed the native scenario limit");
    }
    let names: Vec<_> = studio
        .shots
        .iter()
        .enumerate()
        .map(|(i, _)| format!("gs_{}_cam_{:03}", &project.id[..8], count + i))
        .collect();
    append_camera_points(&studio.shots,&names,scenario,workspace,edit,runner)?;
    let scenario_path = safe_relative(scenario)?;
    let parent = scenario_path.parent().unwrap_or(Path::new(""));
    let directory = workspace.join("data").join(parent).join("scripts");
    fs::create_dir_all(&directory)?;
    let mut source = script(&names, &studio.shots, options)?;
    let manifest = workspace.join("animation-manifest.json");
    if manifest.is_file() {
        let record: serde_json::Value = serde_json::from_slice(&fs::read(manifest)?)?;
        let actions: Vec<crate::animations::NativeAnimationAction> = serde_json::from_value(
            record
                .get("actions")
                .cloned()
                .unwrap_or_else(|| serde_json::json!([])),
        )?;
        let mut play = String::new();
        for action in actions.iter().filter(|a| a.play_on_take) {
            safe_relative(&action.graph)?;
            if action.animation.len() > 31
                || !action
                    .animation
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || c == b'_')
            {
                return invalid("Invalid native animation action name");
            }
            play.push_str(&format!("  (if (custom_animation (unit (list_get (players) 0)) \"{}\" \"{}\" true) (log_print \"Spark native animation started\") (log_print \"Spark native animation unavailable\"))\n",action.graph,action.animation));
        }
        if !play.is_empty() {
            source = source.replacen("  (camera_set", &format!("{play}  (camera_set"), 1);
            source=source.replacen("  (camera_control false)","  (if (> (list_count (players)) 0) (unit_stop_custom_animation (unit (list_get (players) 0))))\n  (camera_control false)",1);
        }
    }
    project::atomic_write(
        &directory.join("gs_machinima.hsc"),
        source.as_bytes(),
        false,
    )?;
    let compiler = edit
        .parent()
        .ok_or_else(|| SparkError::Invalid("Script compiler folder unavailable".into()))?
        .join(if cfg!(windows) {
            "invader-script.exe"
        } else {
            "invader-script"
        });
    crate::reject_links(&compiler)?;
    if !compiler.is_file() {
        return invalid("In-engine camera takes require invader-script alongside invader-edit");
    }
    let mut compile_args=vec!["-g".into(),"mcc-cea".into(),"-t".into(),tags.to_string_lossy().into_owned(),
        "-d".into(),workspace.join("data").to_string_lossy().into_owned(),"-x".into(),"gs_machinima".into()];
    // Include only the original embedded modules and this generated take.
    // An unrelated global_scripts.hsc in the workspace is never adopted.
    if !inherited_sources.iter().any(|name|name=="global_scripts") {compile_args.push("-E".into());}
    for name in inherited_sources.iter().filter(|name|name.as_str()!="global_scripts") {
        compile_args.extend(["-x".into(),name.clone()]);
    }
    compile_args.push(scenario.into());
    let compiler_hash=crate::maps::hash_file(&compiler)?;
    runner.run(&compiler,&compile_args,workspace,"engine-script",52)?;
    if crate::maps::hash_file(&compiler)?!=compiler_hash {return invalid("Native script compiler changed during source merging");}
    let final_scripts=read_names("scripts",1024)?;
    let final_globals=read_names("globals",512)?;
    let final_sources=read_names("source_files",16)?;
    if final_scripts.len()!=inherited_scripts.len()+generated_scripts || final_globals.len()!=inherited_globals.len()+3 || final_sources.len()!=inherited_sources.len()+1 {
        return invalid("Recovered source compiled a different script/global/module inventory beyond the camera controls. Review that source before adopting the build");
    }
    for name in ["gs_record_stop","gs_record_start","gs_mc_initialize","gs_mc_controls"] {
        if final_scripts.iter().filter(|value|value.as_str()==name).count()!=1 {return invalid(format!("Native camera controller is missing or ambiguous: {name}"));}
    }
    if options.playback=="sequence" && final_scripts.iter().filter(|name|name.as_str()=="gs_mc_sequence").count()!=1 {
        return invalid("Native camera sequence controller is missing or ambiguous");
    }
    for name in ["gs_mc_active","gs_mc_ready","gs_mc_flash"] {
        if final_globals.iter().filter(|value|value.as_str()==name).count()!=1 {return invalid(format!("Native camera global is missing or ambiguous: {name}"));}
    }
    for (original,actual,kind) in [(&inherited_scripts,&final_scripts,"script"),(&inherited_globals,&final_globals,"global"),(&inherited_sources,&final_sources,"source module")] {
        for name in original {
            if actual.iter().filter(|candidate|*candidate==name).count()<original.iter().filter(|candidate|*candidate==name).count() {
                return invalid(format!("Native camera compilation lost an original {kind}: {name}"));
            }
        }
    }
    for (relative,expected) in &recovered_sources {
        if crate::maps::hash_file(&workspace.join(safe_relative(relative)?))? != *expected {
            return invalid("Recovered gameplay source changed while compiling the camera take");
        }
    }
    project::atomic_write(
        &workspace.join("engine-machinima.json"),
        &serde_json::to_vec_pretty(
            &serde_json::json!({"schemaVersion":2,"sourceMode":if original_scripts.is_none(){"authored"}else{"recovered"},"inheritedScripts":inherited_scripts,"inheritedGlobals":inherited_globals,"recoveredSourceHashes":recovered_sources,"sourceRecoveryToolSha256":source_recovery_tool,"scriptCompilerSha256":compiler_hash,"scenario":scenario,"scenarioSha256":crate::maps::hash_file(&tags.join(safe_relative(&format!("{scenario}.scenario"))?))?,"projectFingerprint":project.fingerprint()?,"cameras":names,"options":options,"hud":"hidden during takes; restored on stop","actorInput":true,"recording":"OBS Game Capture at game resolution; editor capture limits do not apply","runtimeAcceptance":"pending"}),
        )?,
        false,
    )?;
    Ok(())
}
/// One native camera-point writer for recording takes and reviewed campaign intros.
/// Append only inside an owned build workspace; existing points/indices are retained.
pub(crate) fn append_camera_points(shots:&[CameraShot],names:&[String],scenario:&str,workspace:&Path,edit:&Path,runner:&Runner<'_>)->Result<()> {
    let tags=workspace.join("tags");let tag=format!("{scenario}.scenario");
    let count=runner.run(edit,&["-t".into(),tags.to_string_lossy().into_owned(),"-C".into(),"cutscene_camera_points".into(),tag.clone()],workspace,"engine-camera",47)?.trim().parse::<usize>().map_err(|_|SparkError::Invalid("Camera point count unavailable".into()))?;
    if shots.len()!=names.len()||count+shots.len()>512{return invalid("Native camera point count exceeds the scenario limit");}
    let existing=if count==0{String::new()}else{runner.run(edit,&["-t".into(),tags.to_string_lossy().into_owned(),"-G".into(),"cutscene_camera_points[*].name".into(),tag.clone()],workspace,"engine-camera",48)?};
    let mut occupied=existing.lines().map(|name|name.trim().to_ascii_lowercase()).collect::<std::collections::BTreeSet<_>>();
    for (name,shot) in names.iter().zip(shots) {
        if !crate::creative::script_ident(name)||!occupied.insert(name.to_ascii_lowercase()) {return invalid(format!("Camera point already exists or has an invalid identity: {name}. Existing points were preserved"));}
        camera_angles(shot)?;
        if !shot.fov.is_finite()||!(5.0..=150.0).contains(&shot.fov)||shot.camera_position.iter().any(|v|!v.is_finite()) {return invalid("Invalid native camera position or FOV");}
    }
    for (i, shot) in shots.iter().enumerate() {
        let prefix = format!("cutscene_camera_points[{}]", count + i);
        let angles = camera_angles(shot)?;
        let vector = |v: [f32; 3]| format!("{:.8},{:.8},{:.8}", v[0], v[1], v[2]);
        let mut args = vec![
            "-t".into(),
            tags.to_string_lossy().into_owned(),
            "-I".into(),
            "cutscene_camera_points".into(),
            "1".into(),
            "end".into(),
        ];
        for (field, value) in [
            ("name", names[i].clone()),
            ("position", vector(shot.camera_position)),
            ("orientation", vector(angles)),
            ("field_of_view", format!("{:.8}", shot.fov.to_radians())),
        ] {
            args.extend(["-S".into(), format!("{prefix}.{field}"), value]);
        }
        args.push(tag.clone());
        runner.run(edit, &args, workspace, "engine-camera", 50)?;
    }
    // Independently query the native writer's result before compiling source.
    for (index,(name,shot)) in names.iter().zip(shots).enumerate() {
        let prefix=format!("cutscene_camera_points[{}]",count+index);
        let read=|field:&str|runner.run(edit,&["-t".into(),tags.to_string_lossy().into_owned(),"-G".into(),format!("{prefix}.{field}"),tag.clone()],workspace,"camera-readback",51);
        if read("name")?.trim()!=name {return invalid("Native cinematic marker identity differs after preparation");}
        let angles=camera_angles(shot)?.map(f32::to_degrees);
        for (field,expected) in [("position",shot.camera_position.to_vec()),("orientation",angles.to_vec()),("field_of_view",vec![shot.fov])] {
            // Invader -S consumes radians; its human-readable -G reports degrees.
            let actual=read(field)?.trim().split(',').map(|s|s.trim().parse::<f32>()).collect::<std::result::Result<Vec<_>,_>>().map_err(|_|SparkError::Invalid("Native camera readback is not finite numeric data".into()))?;
            if actual.len()!=expected.len()||actual.iter().zip(expected).any(|(a,b)|!a.is_finite()||(a-b).abs()>0.0001) {return invalid(format!("Native camera {field} differs after preparation"));}
        }
    }
    Ok(())
}
