//! Game-native camera points + HaloScript. The game renders at its own resolution;
//! player input stays enabled. No process injection, OBS capture or HUD mockup.
use crate::{
    build::Runner,
    creative::{CameraShot, EngineMachinima},
    invalid,
    project::{self, Project},
    safe_relative, Result, SparkError,
};
use std::{fs, path::Path};
/// Extend an already owned conversion job for a take. Used by acceptance tools;
/// installed SDK masters and unrelated folders are refused.
pub fn prepare_workspace_take(
    project: &Project,
    scenario: &str,
    workspace: &Path,
    edit: &Path,
    original_scripts: usize,
    on_event: impl Fn(crate::build::JobEvent) + Send + Sync,
) -> Result<()> {
    project.validate()?;
    crate::reject_links(workspace)?;
    crate::reject_links(edit)?;
    let workspace = fs::canonicalize(workspace)?;
    let workspace = workspace.as_path();
    let edit = fs::canonicalize(edit)?;
    let edit = edit.as_path();
    let source = project
        .source
        .as_ref()
        .ok_or_else(|| SparkError::Invalid("An owned converted source is required".into()))?;
    let marker: serde_json::Value =
        serde_json::from_slice(&fs::read(workspace.join("conversion-manifest.json"))?)?;
    if marker
        .get("sourceSha256")
        .and_then(serde_json::Value::as_str)
        != Some(source.sha256.as_str())
        || source.scenario_path != scenario
        || !workspace.join("input-sdk-tags.json").is_file()
    {
        return invalid("Engine take workspace is not the matching owned conversion job");
    }
    let cancel = std::sync::atomic::AtomicBool::new(false);
    let id = uuid::Uuid::new_v4().to_string();
    let runner = Runner {
        id: &id,
        project: &project.id,
        cancel: &cancel,
        event: &on_event,
    };
    prepare(
        project,
        scenario,
        workspace,
        edit,
        &runner,
        original_scripts,
    )
}
pub fn prepare_workspace_animations(
    project: &Project,
    inspection: &crate::maps::MapInspection,
    workspace: &Path,
    tools: &crate::build::Toolchain,
    on_event: impl Fn(crate::build::JobEvent) + Send + Sync,
) -> Result<()> {
    project.validate()?;
    crate::reject_links(workspace)?;
    let workspace = fs::canonicalize(workspace)?;
    let marker: serde_json::Value =
        serde_json::from_slice(&fs::read(workspace.join("conversion-manifest.json"))?)?;
    if marker
        .get("sourceSha256")
        .and_then(serde_json::Value::as_str)
        != Some(inspection.sha256.as_str())
        || !workspace.join("input-sdk-tags.json").is_file()
    {
        return invalid("Animation workspace is not the matching owned conversion job");
    }
    let cancel = std::sync::atomic::AtomicBool::new(false);
    let id = uuid::Uuid::new_v4().to_string();
    let runner = Runner {
        id: &id,
        project: &project.id,
        cancel: &cancel,
        event: &on_event,
    };
    crate::animations::prepare_native(project, inspection, tools, &workspace, &runner)?;
    Ok(())
}
pub fn camera_angles(shot: &CameraShot) -> Result<[f32; 3]> {
    let d: Vec<_> = shot
        .look_at
        .iter()
        .zip(shot.camera_position)
        .map(|(a, b)| a - b)
        .collect();
    let length = d.iter().map(|v| v * v).sum::<f32>().sqrt();
    if !length.is_finite() || length < 0.001 {
        return invalid("Engine camera needs a distinct finite look-at target");
    }
    Ok([
        d[1].atan2(d[0]),
        (d[2] / length).clamp(-1., 1.).asin(),
        shot.roll.unwrap_or(0.).to_radians(),
    ])
}
pub fn script(names: &[String], shots: &[CameraShot], options: &EngineMachinima) -> Result<String> {
    if names.len() != shots.len()
        || names.is_empty()
        || names.len() > 64
        || names
            .iter()
            .any(|n| n.len() > 31 || !n.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_'))
    {
        return invalid("Invalid engine camera binding");
    }
    let selected = options
        .camera_id
        .as_ref()
        .and_then(|id| shots.iter().position(|s| &s.id == id))
        .unwrap_or(0);
    let mut h=String::from("; Generated by Project Guilty Spark. Native game camera, full game resolution.\n; Flashlight toggles the take. Player movement and actions remain enabled.\n(global boolean gs_mc_active false)\n(global boolean gs_mc_ready false)\n(global boolean gs_mc_flash false)\n(script static void gs_record_stop\n  (set gs_mc_active false)\n  (camera_control false)\n  (show_hud true)\n  (cinematic_show_letterbox false)\n  (player_enable_input true)\n  (log_print \"Spark camera stopped; HUD restored\")\n)\n(script static void gs_record_start\n  (camera_control true)\n  (show_hud false)\n  (cinematic_show_letterbox false)\n  (player_enable_input true)\n");
    h.push_str(&format!("  (camera_set {} 0)\n  (set gs_mc_active true)\n  (log_print \"Spark camera active; actor controls enabled\")\n)\n",names[selected]));
    h.push_str("(script startup gs_mc_initialize\n  (sleep_until (> (list_count (players)) 0) 1)\n  (set gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0))))\n  (set gs_mc_ready true)\n");
    if options.auto_start {
        h.push_str("  (gs_record_start)\n");
    }
    h.push_str(")\n(script continuous gs_mc_controls\n  (sleep_until gs_mc_ready 1)\n  (if (> (list_count (players)) 0)\n    (if (not (= gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0)))))\n      (begin\n        (set gs_mc_flash (unit_get_current_flashlight_state (unit (list_get (players) 0))))\n        (if gs_mc_active (gs_record_stop) (gs_record_start))\n      )\n    )\n  )\n  (sleep 1)\n)\n");
    if options.playback == "sequence" {
        h.push_str("(script continuous gs_mc_sequence\n  (sleep_until gs_mc_active 1)\n");
        for (i, name) in names.iter().enumerate() {
            let duration =
                ((shots[i].duration_ms as f64 * 30. / 1000.).round() as u32).clamp(1, 30000);
            let blend = if i == 0 || shots[i].easing.as_deref() == Some("cut") {
                0
            } else {
                duration
            };
            h.push_str(&format!("  (if gs_mc_active (begin (camera_set {name} {blend}) (sleep_until (not gs_mc_active) 1 {duration})))\n"));
        }
        h.push_str("  (if gs_mc_active (gs_record_stop))\n)\n");
    }
    Ok(h)
}
pub(crate) fn prepare(
    project: &Project,
    scenario: &str,
    workspace: &Path,
    edit: &Path,
    runner: &Runner,
    original_scripts: usize,
) -> Result<()> {
    let Some(studio) = &project.studio else {
        return Ok(());
    };
    let Some(options) = studio.engine_machinima.as_ref().filter(|o| o.enabled) else {
        return Ok(());
    };
    studio.validate()?;
    if original_scripts > 0 {
        return invalid("This scenario already has scripts. Recover and merge their original source before adding an engine camera take; Spark will not replace authored gameplay scripts");
    }
    let tags = workspace.join("tags");
    let tag = format!("{scenario}.scenario");
    let args = vec![
        "-t".into(),
        tags.to_string_lossy().into_owned(),
        "-C".into(),
        "cutscene_camera_points".into(),
        tag.clone(),
    ];
    let count = runner
        .run(edit, &args, workspace, "engine-camera", 48)?
        .trim()
        .parse::<usize>()
        .map_err(|_| SparkError::Invalid("Camera point count unavailable".into()))?;
    if count + studio.shots.len() > 512 {
        return invalid("Engine camera points exceed the native scenario limit");
    }
    let names: Vec<_> = studio
        .shots
        .iter()
        .enumerate()
        .map(|(i, _)| format!("gs_{}_cam_{:03}", &project.id[..8], count + i))
        .collect();
    for (i, shot) in studio.shots.iter().enumerate() {
        let prefix = format!("cutscene_camera_points[{}]", count + i);
        let angles = camera_angles(shot)?;
        let vector = |v: [f32; 3]| format!("{:.8},{:.8},{:.8}", v[0], v[1], v[2]);
        let mut args = vec![
            "-t".into(),
            tags.to_string_lossy().into_owned(),
            "-I".into(),
            "cutscene_camera_points".into(),
            "1".into(),
            "end".into(),
        ];
        for (field, value) in [
            ("name", names[i].clone()),
            ("position", vector(shot.camera_position)),
            ("orientation", vector(angles)),
            ("field_of_view", format!("{:.8}", shot.fov.to_radians())),
        ] {
            args.extend(["-S".into(), format!("{prefix}.{field}"), value]);
        }
        args.push(tag.clone());
        runner.run(edit, &args, workspace, "engine-camera", 50)?;
    }
    let scenario_path = safe_relative(scenario)?;
    let parent = scenario_path.parent().unwrap_or(Path::new(""));
    let directory = workspace.join("data").join(parent).join("scripts");
    fs::create_dir_all(&directory)?;
    let mut source = script(&names, &studio.shots, options)?;
    let manifest = workspace.join("animation-manifest.json");
    if manifest.is_file() {
        let record: serde_json::Value = serde_json::from_slice(&fs::read(manifest)?)?;
        let actions: Vec<crate::animations::NativeAnimationAction> = serde_json::from_value(
            record
                .get("actions")
                .cloned()
                .unwrap_or_else(|| serde_json::json!([])),
        )?;
        let mut play = String::new();
        for action in actions.iter().filter(|a| a.play_on_take) {
            safe_relative(&action.graph)?;
            if action.animation.len() > 31
                || !action
                    .animation
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || c == b'_')
            {
                return invalid("Invalid native animation action name");
            }
            play.push_str(&format!("  (if (custom_animation (unit (list_get (players) 0)) \"{}\" \"{}\" true) (log_print \"Spark native animation started\") (log_print \"Spark native animation unavailable\"))\n",action.graph,action.animation));
        }
        if !play.is_empty() {
            source = source.replacen("  (camera_set", &format!("{play}  (camera_set"), 1);
            source=source.replacen("  (camera_control false)","  (if (> (list_count (players)) 0) (unit_stop_custom_animation (unit (list_get (players) 0))))\n  (camera_control false)",1);
        }
    }
    project::atomic_write(
        &directory.join("gs_machinima.hsc"),
        source.as_bytes(),
        false,
    )?;
    let globals = workspace.join("data/global_scripts.hsc");
    if !globals.exists() {
        project::atomic_write(
            &globals,
            b"; Spark owned take: no original global script definitions.\r\n",
            false,
        )?;
    }
    let compiler = edit
        .parent()
        .ok_or_else(|| SparkError::Invalid("Script compiler folder unavailable".into()))?
        .join(if cfg!(windows) {
            "invader-script.exe"
        } else {
            "invader-script"
        });
    crate::reject_links(&compiler)?;
    if !compiler.is_file() {
        return invalid("In-engine camera takes require invader-script alongside invader-edit");
    }
    runner.run(
        &compiler,
        &[
            "-g".into(),
            "mcc-cea".into(),
            "-t".into(),
            tags.to_string_lossy().into_owned(),
            "-d".into(),
            workspace.join("data").to_string_lossy().into_owned(),
            scenario.into(),
        ],
        workspace,
        "engine-script",
        52,
    )?;
    let sources = runner.run(
        edit,
        &[
            "-t".into(),
            tags.to_string_lossy().into_owned(),
            "-C".into(),
            "source_files".into(),
            tag,
        ],
        workspace,
        "engine-script",
        53,
    )?;
    if sources
        .trim()
        .parse::<usize>()
        .ok()
        .filter(|n| *n > 0)
        .is_none()
    {
        return invalid("Native camera script source was not embedded in the scenario");
    }
    project::atomic_write(
        &workspace.join("engine-machinima.json"),
        &serde_json::to_vec_pretty(
            &serde_json::json!({"schemaVersion":2,"scenario":scenario,"scenarioSha256":crate::maps::hash_file(&tags.join(safe_relative(&format!("{scenario}.scenario"))?))?,"projectFingerprint":project.fingerprint()?,"cameras":names,"options":options,"hud":"hidden during takes; restored on stop","actorInput":true,"recording":"OBS Game Capture at game resolution; editor capture limits do not apply","runtimeAcceptance":"pending"}),
        )?,
        false,
    )?;
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    fn shot() -> CameraShot {
        CameraShot {
            id: "a".into(),
            name: "A".into(),
            duration_ms: 1000,
            camera_position: [0., 0., 0.],
            look_at: [0., 1., 0.],
            fov: 70.,
            subtitle: String::new(),
            camera_marker: None,
            roll: Some(90.),
            easing: None,
        }
    }
    #[test]
    fn game_angles_use_halo_z_up_radians() {
        let a = camera_angles(&shot()).unwrap();
        assert!((a[0] - std::f32::consts::FRAC_PI_2).abs() < 1e-5);
        assert_eq!(a[1], 0.);
        assert!((a[2] - std::f32::consts::FRAC_PI_2).abs() < 1e-5);
        let mut s = shot();
        s.look_at = s.camera_position;
        assert!(camera_angles(&s).is_err());
    }
    #[test]
    fn native_take_preserves_actor_input_and_restores_hud() {
        let h = script(
            &["gs_cam_0".into()],
            &[shot()],
            &EngineMachinima {
                enabled: true,
                playback: "fixed".into(),
                camera_id: None,
                auto_start: false,
            },
        )
        .unwrap();
        assert!(h.contains("(show_hud false)"));
        assert!(h.contains("(show_hud true)"));
        assert!(h.contains("(player_enable_input true)"));
        assert!(!h.contains("cinematic_start"));
        assert!(!h.contains("player_enable_input false"));
        assert!(script(
            &["camera\nquit".into()],
            &[shot()],
            &EngineMachinima {
                enabled: true,
                playback: "fixed".into(),
                camera_id: None,
                auto_start: false
            }
        )
        .is_err());
    }
}
