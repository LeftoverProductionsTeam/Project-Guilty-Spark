import assert from 'node:assert/strict';
import { assembleHceekSourcePack,scenarioSlug } from '../src/hceekSourcePack.ts';
import { sourceZip,sourceTreeZip } from '../src/sourceZip.ts';
import { emptyCreatorStudio } from '../src/creatorStudio.ts';
assert.equal(scenarioSlug('First Contact'), 'first_contact');
assert.equal(scenarioSlug('X😀Y'), 'x_y', 'Unicode codepoints follow Rust source slug logic');
assert.equal(scenarioSlug('ABC...' + 'X'.repeat(80)).length,31);
assert.throws(()=>scenarioSlug('../../'),/slug/);
const studio=emptyCreatorStudio();
studio.missions=[{id:'1',title:'Bridge',objective:'Enter',trigger:'manual',encounterName:''}];
const project={id:'prj',title:'First Contact',quickForge:{name:'First Contact',runtimeId:'haloCustomEdition',gameMode:'firefight'},studio,firefight:null};
const stage=assembleHceekSourcePack(project,'mission');
assert.equal(stage.scenarioPath,'levels\\quickforge\\first_contact\\first_contact');
assert.ok(stage.files.some(f=>f.name==='data/levels/quickforge/first_contact/scripts/gs_mission.hsc'));
assert.ok(stage.files.some(f=>f.name.endsWith('/gs_bootstrap.hsc')&&f.contents.includes('(wake gs_mission)')));
assert.equal(JSON.parse(stage.files.find(f=>f.name==='READ_ME_FIRST.json').contents).gameplayVerified,false);
assert.deepEqual([...assembleHceekSourcePack(project,'mission').bytes], [...stage.bytes], 'source ZIP is deterministic');
assert.throws(()=>assembleHceekSourcePack(project,'firefight'),/No Firefight/);
assert.throws(()=>assembleHceekSourcePack({...project,quickForge:{...project.quickForge,gameMode:'slayer'}},'mission'),/singleplayer/);
assert.throws(()=>assembleHceekSourcePack({...project,quickForge:{...project.quickForge,name:'../../'}},'mission'),/slug/);
assert.throws(()=>sourceTreeZip([{name:'../malicious.hsc',contents:'bad'}]),/Unsafe/);
assert.throws(()=>sourceTreeZip([{name:'data/../../malicious.hsc',contents:'bad'}]),/Unsafe/);
assert.throws(()=>sourceTreeZip([{name:'a\\b.hsc',contents:'bad'}]),/Unsafe/);
assert.throws(()=>sourceZip([{name:'data/something.hsc',contents:'bad'}]),/Unsafe/);
console.log('PASS: HCEEK scenario data-tree handoff, review-only startup, deterministic ZIP and path-traversal defense');
