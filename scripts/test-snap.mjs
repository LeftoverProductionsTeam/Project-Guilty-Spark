import assert from 'node:assert/strict';
import { snapBrushToAuthoredMesh } from '../src/snapGeometry.ts';
const brush=(id,kind,pos,dim,rot=[0,0,0])=>({id,name:id,kind,position:pos,dimensions:dim,rotation:rot,materialId:'stone',steps:12,visible:true,locked:false});
const floor=brush('floor','floor',[0,0,0],[8,8,1]);
const box=brush('box','box',[0,0,1.6],[2,2,2]);
let match=snapBrushToAuthoredMesh(box,[floor,box]);
assert.equal(match?.targetBrushId,'floor');
assert.equal(match?.kind,'face');
assert.equal(match?.axis,'z');
assert.deepEqual(match?.position,[0,0,1.5]);
assert.equal(snapBrushToAuthoredMesh(box,[{...floor,visible:false},box]),null);
assert.equal(snapBrushToAuthoredMesh({...box,position:[0,10,1.6]},[floor]),null);
assert.equal(snapBrushToAuthoredMesh({...box,rotation:[0,0,Math.PI/3]},[floor]),null);
assert.equal(snapBrushToAuthoredMesh({...box,locked:true},[floor]),null);
const b=brush('b','box',[1.65,0,0],[2,2,2]),a=brush('a','box',[-0.5,0,0],[2,2,2]);
match=snapBrushToAuthoredMesh(b,[a]);assert.equal(match?.axis,'x');assert.ok(Math.abs(match.position[0]-1.5)<1e-7);
const tunnel=(id,y)=>brush(id,'caveTunnel',[0,y,0],[4,8,4]);
match=snapBrushToAuthoredMesh(tunnel('b',8.4),[tunnel('a',0),tunnel('b',8.4)]);
assert.equal(match?.kind,'cave-rim');assert.deepEqual(match?.position,[0,8,0]);
assert.equal(snapBrushToAuthoredMesh(tunnel('b',8.4),[tunnel('a',0),tunnel('c',0),tunnel('b',8.4)]),null,'ambiguous duplicate rim');
assert.equal(snapBrushToAuthoredMesh({...tunnel('b',8.4),steps:10},[tunnel('a',0)]),null);
assert.equal(snapBrushToAuthoredMesh({...tunnel('b',8.4),rotation:[0,0,Math.PI/3]},[tunnel('a',0)]),null);
assert.throws(()=>snapBrushToAuthoredMesh(box,[floor],100),/reach/);
assert.throws(()=>snapBrushToAuthoredMesh({...box,position:[NaN,0,0]},[floor]),/non-finite/);
console.log('PASS: opt-in face and exact cave-rim snapping, rotations, hidden/locked, ambiguous and unsafe placements');
