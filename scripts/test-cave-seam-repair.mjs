import assert from 'node:assert/strict';
import { auditCaveExtensions, planCaveSeamSnap, applyCaveSeamSnap } from '../src/caveSeamRepair.ts';
import { analyzeCaveJoins } from '../src/caveJoinAnalysis.ts';
const tunnel=(id,y,locked=false)=>({id,kind:'caveTunnel',name:id,position:[0,y,0],rotation:[0,0,0],dimensions:[4,8,4],steps:12,visible:true,locked,materialId:'rock'});
const room=(id,y)=>({id,kind:'room',name:id,position:[0,y,0],rotation:[0,0,0],dimensions:[20,20,20],steps:4,visible:true,locked:false,materialId:'rock'});
const original={geometry:[tunnel('first',0),tunnel('second',8.12)]};
const audit=auditCaveExtensions(original);
assert.equal(audit.issues.filter(i=>i.code==='TUNNEL_GAP').length,1);
assert.equal(audit.corrections.length,1);
assert.equal(audit.compiledCollisionVerified,false);
assert.equal(audit.corrections[0].movingBrushId,'second');
assert.ok(Math.abs(audit.corrections[0].distance-.12)<1e-8);
const fixed=applyCaveSeamSnap(original,audit.corrections[0]);
assert.notStrictEqual(fixed,original,'repairs create a separate document for undo/redo');
assert.equal(original.geometry[1].position[1],8.12,'must never mutate input');
assert.equal(fixed.geometry[1].position[1],8);
assert.equal(analyzeCaveJoins(fixed).weldedPairs,1);
assert.equal(auditCaveExtensions(fixed).issues.length,0);
assert.throws(()=>applyCaveSeamSnap({...original,geometry:[tunnel('first',0),tunnel('second',8.2)]},audit.corrections[0]),/changed/i);
assert.throws(()=>planCaveSeamSnap({geometry:[tunnel('first',0),tunnel('second',8.12,true)]},'second','first'),/locked/i);
assert.throws(()=>planCaveSeamSnap({geometry:[tunnel('first',0),tunnel('second',8.6)]},'second','first'),/No unique/);
assert.equal(auditCaveExtensions({geometry:[tunnel('first',0),tunnel('second',8.12,true)]}).corrections.length,0,'locked source never gets an automatic repair');
const bad={geometry:[tunnel('first',0),{...tunnel('second',8),dimensions:[5,8,4]}]};
assert.ok(auditCaveExtensions(bad).issues.some(i=>i.code==='TUNNEL_INCOMPATIBLE'));
assert.throws(()=>planCaveSeamSnap(bad,'second','first'),/different/);
const ambiguous={geometry:[tunnel('first',0),tunnel('second',8),tunnel('third',8)]};
assert.ok(auditCaveExtensions(ambiguous).issues.some(i=>i.code==='TUNNEL_THREE_WAY'));
assert.equal(auditCaveExtensions({geometry:[...Array(33)].map((_,i)=>tunnel('x'+i,i*20))}).complete,false);
const uncut={geometry:[tunnel('first',0),room('room',14)]}; // far face y=4, room near wall y=4
assert.ok(auditCaveExtensions(uncut).issues.some(i=>i.code==='TUNNEL_ROOM_UNCUT'));
assert.throws(()=>auditCaveExtensions({geometry:[tunnel('first',0),tunnel('first',8)]}),/duplicate/);
console.log('PASS: tunnel gap repair is exact, unique, reversible and stale-safe; incompatible/locked/room-cut/ambiguous source blocked; compiled collision never claimed');
