import assert from 'node:assert/strict';
import { auditInterchangePrecision,assertInterchangePrecision } from '../src/haloInterchangePrecision.ts';
import { exportMeshJms } from '../src/haloJms.ts';
import { exportMeshObj } from '../src/haloObj.ts';
const good={label:'fixture',source:'obj',positions:[0,0,0,1,0,0,0,1,0],indices:[0,1,2],uvs:[0,0,1,0,0,1],normals:[0,0,1,0,0,1,0,0,1]};
assert.equal(auditInterchangePrecision(good,'obj').exportSafe,true);
assert.equal(auditInterchangePrecision(good,'jms').runtimeCollisionVerified,false);
assertInterchangePrecision(good,'obj');
assert.ok(exportMeshObj(good).text.includes('f 1/1/1 2/2/2 3/3/3'));
assert.ok(exportMeshJms(good).text.startsWith('8200'));
const tiny={...good,positions:[0,0,0,0.0000002,0,0,0,0.0000002,0]};
assert.equal(auditInterchangePrecision(tiny,'obj').lostTriangles,1);
assert.throws(()=>exportMeshObj(tiny),/quantization/);
assert.throws(()=>exportMeshJms(tiny),/quantization/);
const atEdge={...good,positions:[1501,0,0,1499,0,0,1500,1,0]};
assert.equal(auditInterchangePrecision(atEdge,'obj').exportSafe,true,'OBJ not limited to Halo BSP coordinates');
assert.equal(auditInterchangePrecision(atEdge,'jms').outOfBoundsVertices,1);
assert.throws(()=>exportMeshJms(atEdge),/HALO_VERTEX_BOUNDS/);
assert.ok(exportMeshObj(atEdge).text.includes('1501'));
assert.throws(()=>auditInterchangePrecision({...good,indices:[0,1,9]},'obj'),/valid bounded/);
console.log('PASS: precision-safe OBJ/JMS source export refuses quantization-collapse and Halo BSP coordinate overflow without editing input');
