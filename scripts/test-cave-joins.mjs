import assert from 'node:assert/strict';
import { analyzeCaveJoins, cavePorts } from '../src/caveJoinAnalysis.ts';
const tunnel=(id,y)=>({id,kind:'caveTunnel',name:id,position:[0,y,0],rotation:[0,0,0],dimensions:[4,8,4],steps:12,visible:true,locked:false,materialId:'stone'});
let report=analyzeCaveJoins({geometry:[tunnel('a',0),tunnel('b',8)]});
assert.equal(report.ports.length,4);
assert.equal(report.candidates.length,1);
assert.deepEqual(report.candidates[0].first.center,[0,4,0]);
assert.equal(report.candidates[0].aligned,true);
assert.equal(report.candidates[0].rimVerticesMatch,true);
assert.equal(report.candidates[0].sourceWeldEligible,true);
assert.equal(report.weldedPairs,1);
assert.equal(report.candidates[0].joinReady,false);
assert.equal(report.unpaired.length,2);
assert.equal(report.compileReady,false);
report=analyzeCaveJoins({geometry:[tunnel('a',0),{...tunnel('b',8),rotation:[0,0,Math.PI/2]}]});
assert.equal(report.candidates.length,0);
report=analyzeCaveJoins({geometry:[tunnel('a',0),{...tunnel('b',8),dimensions:[5,8,4]}]});
assert.equal(report.candidates.length,1);
assert.equal(report.candidates[0].sameRadii,false);
assert.equal(report.weldedPairs,0);
assert.equal(report.unpaired.length,4);
report=analyzeCaveJoins({geometry:[tunnel('a',0),{...tunnel('b',8),rotation:[0,Math.PI/12,0]}]});
assert.equal(report.candidates.length,1);
assert.equal(report.candidates[0].rimVerticesMatch,false);
assert.equal(report.weldedPairs,0);
report=analyzeCaveJoins({geometry:[tunnel('a',0),tunnel('b',8),tunnel('c',8)]});
assert.equal(report.weldedPairs,0, 'three-way ambiguous mouth must not be welded');
assert.deepEqual(cavePorts(tunnel('x',0))[0].outward,[0,-1,0]);
assert.throws(()=>cavePorts({...tunnel('x',0),position:[NaN,0,0]}),/Invalid/);
console.log('PASS: exact cave rim topology, unique source seam, incompatible/ambiguous guards, no false gameplay proof');
