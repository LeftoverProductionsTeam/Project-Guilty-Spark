import assert from 'node:assert/strict';
import { exportMeshObj } from '../src/haloObj.ts';
const mesh={positions:[0,0,0,1,0,0,0,1,0],normals:[0,0,1,0,0,1,0,0,1],uvs:[0,0,1,0,0,1],indices:[0,1,2],label:'x',source:'halo-render-untextured',materialRanges:[{indexStart:0,indexCount:3,shaderTagId:0x1234,bspIndex:0,lightmapIndex:1}]};
let obj=exportMeshObj(mesh,'bloodgulch BSP');
assert.equal(obj.triangles,1);assert.equal(obj.vertices,3);assert.equal(obj.groups,1);
assert.match(obj.text,/^g shader_1234_bsp0_lm1$/m);
assert.match(obj.text,/^usemtl shader_1234_bsp0_lm1$/m);
assert.match(obj.text,/^f 1\/1\/1 2\/2\/2 3\/3\/3$/m);
assert.equal(exportMeshObj({...mesh,uvs:[]}).includesUvs,false);
assert.match(exportMeshObj({...mesh,materialRanges:[]}).text,/^g geometry$/m);
assert.match(exportMeshObj({...mesh,materialRanges:[],parts:[{name:'metal wall',indexStart:0,indexCount:3}]}).text,/^g part_metal_wall$/m);
assert.throws(()=>exportMeshObj({...mesh,positions:[NaN,...mesh.positions.slice(1)]}),/Invalid or extreme/);
assert.throws(()=>exportMeshObj({...mesh,uvs:[1]}),/Incomplete or corrupt/);
assert.throws(()=>exportMeshObj({...mesh,normals:[1]}),/Incomplete or corrupt/);
assert.throws(()=>exportMeshObj({...mesh,indices:[0,0,2]}),/Degenerate OBJ/);
assert.throws(()=>exportMeshObj({...mesh,indices:[0,1,100]}),/Invalid mesh vertex/);
assert.throws(()=>exportMeshObj({...mesh,materialRanges:[{...mesh.materialRanges[0],indexCount:4}]}),/surface group range/g);
assert.throws(()=>exportMeshObj({...mesh,materialRanges:[...mesh.materialRanges,...mesh.materialRanges]}),/surface group range/g);
console.log('PASS: real indexed OBJ positions/UVs/normals/material spans and malformed geometry guards');
