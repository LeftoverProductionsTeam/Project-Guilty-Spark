import assert from 'node:assert/strict';
import {inspectScenarioRisks} from '../src/scenarioSafety.ts';
const doc={geometry:[],placements:[],spawns:[],objectives:[],gameMode:'slayer'};
assert.deepEqual(inspectScenarioRisks(doc),[]);
const placed={id:'a',name:'biped',tagPath:'characters\\marine',tagClass:'bipd',sourceSha256:'1'.repeat(64),sourceProjectId:'project'};
const issues=inspectScenarioRisks({...doc,placements:[placed,{...placed,id:'b',sourceSha256:'2'.repeat(64)}]});
assert(issues.some(i=>i.code==='CONFLICTING_TAG_ORIGINS'&&i.severity==='error'));
assert(issues.some(i=>i.code==='UNSYNCED_MULTIPLAYER_AI'));
const spawns=[{id:'s1',position:[0,0,1]}, {id:'s2',position:[0,0,1]},{id:'s3',position:[.8,0,1]}];
const congested=inspectScenarioRisks({...doc,spawns});
assert(congested.some(i=>i.code==='DUPLICATE_SPAWN_POSITION' && i.severity==='error'));
assert(congested.some(i=>i.code==='CROWDED_SPAWNS'));
const firefight={waves:[{name:'flood wave',groups:[{count:16},{count:12}]}],maxTotalPerWave:20,maxAlive:8,spawnZones:[]};
const report=inspectScenarioRisks({...doc,gameMode:'zombie'},firefight,{resources:[{name:'bitmaps.map',required:true,found:false,reason:'not supplied'}]});
assert(report.some(i=>i.code==='WAVE_EXCEEDS_CONFIGURED_BUDGET'&&i.severity==='error'));
assert(report.some(i=>i.code==='WAVE_CONCURRENCY_PRESSURE'));
assert(report.some(i=>i.code==='MISSING_EXTERNAL_RESOURCE'));
const empty=inspectScenarioRisks({...doc,geometry:[{kind:'caveTunnel'}]});
assert(empty.some(i=>i.code==='CAVE_BSP_REBUILD_REQUIRED' && i.severity==='info'));
console.log('PASS: deterministic scenario safety risks for legacy collisions, tag provenance, AI count and resource loss');
