export function searchFeatures(query: string, category = 'All'): SparkFeature[] {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return SPARK_FEATURES.filter(
    (f) =>
      (category === 'All' || f.category === category) &&
      words.every((word) =>
        `${f.title} ${f.summary} ${f.category} ${f.steps.join(' ')} ${f.limit ?? ''}`
          .toLowerCase()
          .includes(word),
      ),
  );
}
